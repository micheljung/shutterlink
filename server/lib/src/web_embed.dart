import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:path/path.dart' as p;

/// The files served under `/static/`, in dependency order: a `{{v:<file>}}`
/// placeholder may only name a file listed before the one that holds it.
const List<String> webSources = [
  'logo.svg',
  'manrope-600.woff2',
  'manrope-800.woff2',
  'photoswipe.css',
  'photoswipe.esm.min.js',
  'photoswipe-lightbox.esm.min.js',
  'app.css',
  'gallery.js',
];

const int versionLength = 12;
const String placeholderStart = '{{v:';
const String _rawQuotes = "'''";

const Map<String, String> _contentTypes = {
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.woff2': 'font/woff2',
};

const Set<String> _binaryExtensions = {'.woff2'};

final RegExp _placeholder = RegExp(r'\{\{v:([^{}]*)\}\}');

class WebAsset {
  const WebAsset(this.contentType, this.version, this.bytes);

  final String contentType;
  final String version;
  final List<int> bytes;
}

class EmbedException implements Exception {
  const EmbedException(this.message);

  final String message;

  @override
  String toString() => 'EmbedException: $message';
}

String versionOf(List<int> bytes) =>
    sha256.convert(bytes).toString().substring(0, versionLength);

String contentTypeOf(String name) =>
    _contentTypes[p.extension(name)] ??
    (throw EmbedException('no content type for $name'));

bool _isBinary(String name) => _binaryExtensions.contains(p.extension(name));

Future<Map<String, List<int>>> readWebSources(Directory web) async => {
  for (final name in webSources)
    name: await File(p.join(web.path, name)).readAsBytes(),
};

/// Substitutes every placeholder with its target's version and hashes the
/// result, in [webSources] order.
Map<String, WebAsset> buildWebAssets(Map<String, List<int>> sources) {
  final built = <String, WebAsset>{};
  for (final name in webSources) {
    final source = sources[name] ?? (throw EmbedException('missing web/$name'));
    final bytes = _isBinary(name)
        ? source
        : utf8.encode(_substitute(name, utf8.decode(source), built));
    built[name] = WebAsset(contentTypeOf(name), versionOf(bytes), bytes);
  }
  return built;
}

String _substitute(String name, String text, Map<String, WebAsset> built) {
  final result = text.replaceAllMapped(_placeholder, (match) {
    final target = match[1]!;
    final asset = built[target];
    if (asset != null) return asset.version;
    if (webSources.contains(target)) {
      throw EmbedException('$name references $target before it is built');
    }
    throw EmbedException('$name references unknown file $target');
  });
  if (result.contains(placeholderStart)) {
    throw EmbedException('unresolved placeholder in $name');
  }
  return result;
}

/// Dart source for `web_assets.g.dart`. Text goes into raw string literals;
/// binary files, and text with carriage returns (which Dart normalises
/// inside literals), go in as base64.
String generateWebAssetsSource(Map<String, WebAsset> assets) {
  final out = StringBuffer()
    ..writeln('// Generated by tool/embed_web.dart from web/. Do not edit.')
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'web_embed.dart';")
    ..writeln()
    ..writeln('final Map<String, WebAsset> webAssets = {');
  for (final MapEntry(key: name, value: asset) in assets.entries) {
    out.writeln(
      "  '$name': WebAsset('${asset.contentType}', '${asset.version}', "
      '${_literal(name, asset.bytes)}),',
    );
  }
  out.writeln('};');
  return out.toString();
}

String _literal(String name, List<int> bytes) {
  if (_isBinary(name)) return _base64(bytes);
  final text = utf8.decode(bytes);
  if (text.contains('\r')) return _base64(bytes);
  if (text.contains(_rawQuotes)) {
    throw EmbedException('$name contains $_rawQuotes');
  }
  if (text.endsWith("'")) throw EmbedException("$name ends in '");
  // The newline after the opening quotes is dropped by Dart, so text that
  // itself starts with a blank line survives.
  return "utf8.encode(r'''\n$text''')";
}

String _base64(List<int> bytes) => "base64Decode('${base64Encode(bytes)}')";
